#!/usr/bin/env python3
"""Render a model card (Markdown) from a track's metrics.json and model.json. Standard library only.

    python3 scripts/model_card.py tracks/python/out/metrics.json tracks/python/out/model.json > out/MODEL_CARD.md
    python3 scripts/model_card.py --check docs/model-card.md \
        contract/golden/metrics-2026-05.json contract/golden/model-2026-05.json

The card is generated, never hand-edited: every number comes from the files, so it cannot drift from the model.
The words around the numbers (intended use, limits, ethics) are in this script; change them with a PR.
--check exits 1 if the committed card differs from what the files produce (CI runs it).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def pct(x: float | None, digits: int = 1) -> str:
    return "n/a" if x is None else f"{x * 100:.{digits}f} %"


def num(x: float | None, digits: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def inr(x: float) -> str:
    return f"₹{x:,.0f}"


def display_names() -> dict:
    names = {}
    path = ROOT / "contract" / "data-contract.yaml"
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith("- {name:") and "display:" in line:
            name = line.split("name:", 1)[1].split(",", 1)[0].strip()
            names[name] = line.split('display: "', 1)[1].split('"', 1)[0]
    return names


def monitoring_lines(m: dict, a: dict) -> list[str]:
    """v1.1: how the deployed model did after release, and why this artefact replaced it."""
    mon, rt = m["monitoring"], m["retraining"]
    c, lin = rt["challenger"], a.get("lineage", {})
    out = [
        "## Monitoring and retraining (v1.1)",
        "",
        f"Deployed model {mon['deployed_model']['model_version']} on the months after release "
        f"(PSI against the {mon['reference']['rows']:,} training rows):",
        "",
        "| Month | Role | Rows | AUC | Brier | ECE | Mean predicted | Observed | Score PSI | Drifted features |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    perf = {p["snapshot"]: p for p in mon["performance"]}
    for d in mon["drift"]:
        p = perf.get(d["snapshot"])
        cells = (
            [num(p["auc"]), num(p["brier"], 4), num(p["ece"], 4), pct(p["mean_pred"]), pct(p["observed_rate"])]
            if p
            else ["n/a (no label yet)", "", "", "", ""]
        )
        drifted = ", ".join(f"`{f}` ({num(d['feature_psi'][f])})" for f in d["features_drift"]) or "none"
        out.append(
            f"| {d['snapshot']} | {d['split']} | {d['rows']:,} | "
            + " | ".join(cells)
            + f" | {num(d['score_psi'])} | {drifted} |"
        )
    out += ["", f"Monitoring status: **{mon['status']}**.", ""]
    out += [
        f"**This artefact ({a['model_version']})** is the challenger: the {len(c['features'])} features of "
        f"{a['experiment']}, refitted on {c['refit_snapshots'][0]} to {c['refit_snapshots'][-1]} "
        f"({c['refit_rows']:,} customer-months), then its intercept shifted by {num(c['calibration_offset'], 4)} "
        f"so its mean prediction matches {c['calibration_snapshot']}. Parent model: "
        f"{lin.get('parent_model_version')}. Champion and challenger were compared on {rt['holdout']['snapshot']} "
        f"({rt['holdout']['rows']:,} customers, churn {pct(rt['holdout']['churn_rate'])}), which neither had seen:",
        "",
        "| Holdout metric | Champion | Challenger |",
        "|---|---|---|",
    ]
    ch, cc = rt["champion_holdout"], rt["challenger_holdout"]
    for key, label, digits in (
        ("auc", "AUC", 3),
        ("brier", "Brier", 4),
        ("ece", "ECE", 4),
        ("precision_at_top", "Precision, top 10 %", 3),
        ("recall_gap", "Recall gap", 3),
    ):
        out.append(f"| {label} | {num(ch[key], digits)} | {num(cc[key], digits)} |")
    out += ["", "| Retraining check | Value | Threshold | Result |", "|---|---|---|---|"]
    for g in rt["gate"]["checks"]:
        out.append(
            f"| {g['id']} | {num(g['value'], 4)} | {num(g['threshold'], 4)} | {'pass' if g['passed'] else 'FAIL'} |"
        )
    out += [
        "",
        f"**Decision: {rt['decision']}.** The sections above describe the experiment protocol re-run on this "
        "export (training and test months as in v1.0).",
        "",
    ]
    return out


def render(m: dict, a: dict) -> str:
    names = display_names()
    exp = {e["id"]: e for e in m["experiments"]}
    champ = exp[m["champion"]["experiment"]]
    t = m["test"]
    lines = [
        f"# Model card: ChurnCast {a['model_version']}",
        "",
        "> Generated by `scripts/model_card.py` from `metrics.json` and `model.json`; do not edit by hand.",
        "",
        "## Model details",
        f"- **Model:** {champ['name']} (experiment {champ['id']}), unpenalised, maximum likelihood.",
        f"- **Artefact:** `model.json` schema {a['schema_version']}, model version {a['model_version']}, "
        f"trained by the {m['generator']['track']} track ({m['generator']['version']}).",
        "- **Target:** `churned_next_month`: a subscriber with a paid invoice in month M has none in month M+1.",
        f"- **Training data:** export {m['dataset']['export']} (contract {m['dataset']['contract_version']}), "
        f"snapshots {m['split']['train_snapshots'][0]} to {m['split']['train_snapshots'][-1]}: "
        f"{m['split']['train_rows']:,} customer-months, churn rate {pct(m['split']['train_churn_rate'])}.",
        f"- **Test data (out of time):** snapshots {', '.join(m['split']['test_snapshots'])}: "
        f"{m['split']['test_rows']:,} customer-months, churn rate {pct(m['split']['test_churn_rate'])}.",
        "",
        "## Intended use",
        "- Rank this month's active subscribers by risk so the retention team calls the top "
        "10 % (its capacity) first, with the top reasons for each call.",
        "- Not for: pricing an individual customer, refusing service, credit decisions, or any automated action "
        "without a person in the loop. Not validated outside TiffinBox's cities and plans.",
        "",
        "## Evaluation",
        "Cross-validation: 5 folds on the training snapshots, grouped by customer. Test: the two months after "
        "the training window, never used to choose the model.",
        "",
        "| Experiment | CV AUC (mean ± sd) | Test AUC | Test AP | Test Brier | Precision@10 % | Net value / month |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in m["experiments"]:
        star = " **(champion)**" if e["id"] == champ["id"] else ""
        lines.append(
            f"| {e['id']} {e['name']}{star} | {num(e['cv']['auc_mean'])} ± {num(e['cv']['auc_sd'])} | "
            f"{num(e['test']['auc'])} | {num(e['test']['average_precision'])} | {num(e['test']['brier'], 4)} | "
            f"{pct(e['test']['precision_at_top'])} | {inr(e['test']['net_value_inr_per_month'])} |"
        )
    lines += [
        "",
        f"Champion choice: {m['champion']['reason']}.",
        "",
        "### What the numbers mean for the retention team",
        f"Calling the top 10 % each month ({t['contacted']:,} calls over the two test months) reaches "
        f"{t['churners_reached']:,} of the customers who then cancelled: precision {pct(t['precision_at_top'])}, "
        f"recall {pct(t['recall_at_top'])}, {t['lift_at_top']:.1f}x better than calling at random. With the "
        f"contract's assumptions (₹200 per call, 25 % of reached churners stay, 3 months of revenue each) that is "
        f"{inr(t['net_value_inr_per_month'])} a month, against {inr(exp['B1']['test']['net_value_inr_per_month'])} "
        "for today's rule of thumb. The save rate is an assumption until a holdout experiment measures it.",
        "",
        "## Calibration",
        f"Expected calibration error {num(m['calibration']['ece'], 4)} (10 equal-width bins); mean predicted "
        f"{pct(m['calibration']['mean_pred'])} vs observed {pct(m['calibration']['observed_rate'])}.",
        "",
        "| Predicted | n | Mean predicted | Observed |",
        "|---|---|---|---|",
    ]
    for b in m["calibration"]["bins"]:
        if b["n"]:
            lines.append(
                f"| {b['lower']:.1f}-{b['upper']:.1f} | {b['n']:,} | {pct(b['mean_pred'])} | {pct(b['observed'])} |"
            )
    lines += [
        "",
        "## Drivers (standardised coefficients: change in log-odds per standard deviation)",
        "",
        "| Feature | Meaning | Coefficient | Per SD |",
        "|---|---|---|---|",
    ]
    for r in m["champion"]["importance"]:
        lines.append(
            f"| `{r['feature']}` | {names.get(r['feature'], '')} | {r['coefficient']:+.4f} | {r['standardised']:+.3f} |"
        )
    lines += [
        "",
        "Coefficients are associations, not causes: a customer does not churn *because* of a "
        "coefficient, and changing a feature will not necessarily change the outcome.",
        "",
        "## Slices and fairness (test months)",
        "",
    ]
    for dim, rows in m["slices"].items():
        lines += [
            f"**{dim}**",
            "",
            "| Value | n | Churn rate | Mean predicted | AUC | Called | Recall@10 % |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in rows:
            lines.append(
                f"| {r['value']} | {r['n']:,} | {pct(r['churn_rate'])} | {pct(r['mean_pred'])} | "
                f"{num(r['auc'])} | {pct(r['flagged_rate'])} | {pct(r['recall_at_top'])} |"
            )
        lines.append("")
    f = m["fairness"]
    lines += [
        f"Fairness check on `{f['dimension']}` (protected: never a feature): recall gap {num(f['recall_gap'])} "
        f"(limit {f['max_recall_gap']}), called-rate ratio {num(f['flagged_rate_ratio'])} across "
        f"{', '.join(f['groups'])}. {'Passed' if f['passed'] else 'FAILED'}.",
        "",
        "## Leakage scan",
        f"Best single model feature on the training rows: `{m['leakage']['max_feature']}`, AUC "
        f"{num(m['leakage']['max_feature_auc'])} (limit {m['leakage']['limit']}). The leaky column "
        f"`customers.cancellation_reason` alone would score {num(m['leakage']['probe_auc'])}: it is filled in "
        "after a customer leaves, so it is excluded by the contract.",
        "",
        "## Release gate",
        "",
        "| Check | Value | Threshold | Result |",
        "|---|---|---|---|",
    ]
    for c in m["gate"]["checks"]:
        lines.append(
            f"| {c['id']} | {num(c['value'], 4)} | {num(c['threshold'], 4)} | {'pass' if c['passed'] else 'FAIL'} |"
        )
    lines += ["", f"**Gate: {'PASSED' if m['gate']['passed'] else 'FAILED'}.**", ""]
    if "retraining" in m:
        lines += monitoring_lines(m, a)
    lines += [
        "## Limitations and ethical considerations",
        "- Synthetic data: the case study's TiffinBox is fictional; the patterns are realistic, the people are not.",
        "- Unseen drivers: acquisition channel and age band affect churn but are not features (channel has "
        "gaps before March 2025; age band is protected), so some slices are under- or over-predicted.",
        "- Drift: a price change, a new channel or a competitor changes who churns. Monitor feature drift and "
        "calibration monthly and retrain through the champion/challenger gate (Phase 7).",
        "- Explanations are contributions to a linear score, not reasons a customer gave. The optional AI "
        "explainer rewrites them in plain language and is checked by guardrails; it never sees the customer id.",
        "",
    ]
    return "\n".join(lines)


def main(args: list[str]) -> int:
    check = args[:1] == ["--check"]
    if check:
        args = args[1:]
        target = Path(args.pop(0))
    if len(args) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    with open(args[0], encoding="utf-8") as fm, open(args[1], encoding="utf-8") as fa:
        text = render(json.load(fm), json.load(fa))
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"{target} is out of date: python3 scripts/model_card.py {args[0]} {args[1]} > {target}")
            return 1
        print(f"{target} is up to date")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
